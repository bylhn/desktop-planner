const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('planner', {
  load: () => ipcRenderer.invoke('load'),
  saveTodos: (todos) => ipcRenderer.send('save-todos', todos),
  saveSettings: (s) => ipcRenderer.send('save-settings', s),
  onSettings: (cb) => ipcRenderer.on('settings-changed', (_e, s) => cb(s)),
  onWallpaper: (cb) => ipcRenderer.on('wallpaper', (_e, url) => cb(url)),
  onGeometry: (cb) => ipcRenderer.on('geometry', (_e, g) => cb(g)),
  calendarGet: () => ipcRenderer.invoke('calendar-get'),
  calendarRefresh: () => ipcRenderer.invoke('calendar-refresh'),
  onCalendar: (cb) => ipcRenderer.on('calendar-updated', (_e, p) => cb(p)),
  appInfo: () => ipcRenderer.invoke('app-info'),
  updateGet: () => ipcRenderer.invoke('update-get'),
  updateCheck: () => ipcRenderer.send('update-check'),
  updateInstall: () => ipcRenderer.send('update-install'),
  updateDownload: () => ipcRenderer.send('update-download'),
  onUpdate: (cb) => ipcRenderer.on('update-state', (_e, s) => cb(s)),
  openLink: (key) => ipcRenderer.send('open-link', key),
  onGotoDay: (cb) => ipcRenderer.on('goto-day', (_e, k) => cb(k)),
  googleLogin: () => ipcRenderer.invoke('google-login'),
  googleLogout: () => ipcRenderer.invoke('google-logout'),
  googleToggle: (id, on) => ipcRenderer.invoke('google-toggle', id, on),
  googleAddEvent: (calId, ev) => ipcRenderer.invoke('google-add-event', calId, ev),
  googleDeleteEvent: (cal, id) => ipcRenderer.invoke('google-delete-event', cal, id),
  googleUpdateEvent: (cal, id, ev) => ipcRenderer.invoke('google-update-event', cal, id, ev),
});
